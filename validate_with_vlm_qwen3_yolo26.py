#!/usr/bin/env python3
import os
import sys
import argparse
import glob
import gc
import torch
import numpy as np
import cv2
from PIL import Image, ImageDraw, ImageFont
from tqdm import tqdm
from ultralytics import YOLO
from transformers import Qwen3VLForConditionalGeneration, AutoProcessor, BitsAndBytesConfig
from peft import PeftModel
from torchmetrics.detection.mean_ap import MeanAveragePrecision

SYSTEM_PROMPT = "<|im_start|>system\nYou are a helpful assistant.<|im_end|>\n"
ASSISTANT_PREFIX = "<|im_start|>assistant\n"

def parse_args():
    parser = argparse.ArgumentParser(description="Evaluate YOLO + Qwen-VL on the test split.")
    parser.add_argument("--yolo-models", type=str, default="", help="Comma-separated path(s) to YOLO best.pt weights (defaults to all runs if empty)")
    parser.add_argument("--qwen-model", type=str, default="qwen3_vl_model_full3_ra1632", help="Path to Qwen-VL adapter model")
    parser.add_argument("--dataset-dir", type=str, default="1-class-weapon-dataset-2", help="Dataset directory path")
    parser.add_argument("--conf-thres", type=float, default=0.25, help="YOLO confidence threshold")
    parser.add_argument("--iou-thres", type=float, default=0.45, help="YOLO IoU threshold")
    parser.add_argument("--max-images", type=int, default=None, help="Maximum number of images to evaluate (for quick test)")
    parser.add_argument("--txt-output", type=str, default="evaluation_report_yolo26.txt", help="Path to save text report output")
    parser.add_argument("--output-dir", type=str, default="inference_results_yolo26", help="Directory to save annotated result images (set empty to disable)")
    parser.add_argument("--device", type=str, default="cuda", help="Device to run on (cuda or cpu)")
    parser.add_argument("--vlm-bypass-thres", type=float, default=0.75, help="YOLO confidence threshold at or above which VLM verification is bypassed")
    parser.add_argument("--max-pixels", type=int, default=589824, help="Maximum input pixels for Qwen2-VL processor (default 589824 is 768x768)")
    parser.add_argument("--max-new-tokens", type=int, default=200, help="Maximum new tokens generated by Qwen2-VL")
    return parser.parse_args()

def format_qwen_bbox(xmin, ymin, xmax, ymax, img_width, img_height):
    ymin_norm = int(round(ymin / img_height * 1000))
    xmin_norm = int(round(xmin / img_width * 1000))
    ymax_norm = int(round(ymax / img_height * 1000))
    xmax_norm = int(round(xmax / img_width * 1000))
    
    # Clip to [0, 1000]
    ymin_norm = max(0, min(1000, ymin_norm))
    xmin_norm = max(0, min(1000, xmin_norm))
    ymax_norm = max(0, min(1000, ymax_norm))
    xmax_norm = max(0, min(1000, xmax_norm))
    
    return f"<box>({ymin_norm},{xmin_norm},{ymax_norm},{xmax_norm})</box>"

def calculate_iou(box1, box2):
    x1 = max(box1[0], box2[0])
    y1 = max(box1[1], box2[1])
    x2 = min(box1[2], box2[2])
    y2 = min(box1[3], box2[3])
    
    intersection = max(0, x2 - x1) * max(0, y2 - y1)
    area1 = (box1[2] - box1[0]) * (box1[3] - box1[1])
    area2 = (box2[2] - box2[0]) * (box2[3] - box2[1])
    union = area1 + area2 - intersection
    
    if union == 0:
        return 0
    return intersection / union

def compute_image_tp_fp_fn(pred_boxes, pred_scores, gt_boxes, iou_threshold=0.5):
    if len(pred_boxes) == 0:
        return 0, 0, len(gt_boxes)
    if len(gt_boxes) == 0:
        return 0, len(pred_boxes), 0
        
    sort_idx = np.argsort(pred_scores)[::-1]
    pred_boxes = pred_boxes[sort_idx]
    
    tp = 0
    fp = 0
    matched_gt = set()
    
    for p_box in pred_boxes:
        best_iou = 0
        best_gt_idx = -1
        for i, g_box in enumerate(gt_boxes):
            if i in matched_gt:
                continue
            iou = calculate_iou(p_box, g_box)
            if iou > best_iou:
                best_iou = iou
                best_gt_idx = i
                
        if best_iou >= iou_threshold and best_gt_idx != -1:
            tp += 1
            matched_gt.add(best_gt_idx)
        else:
            fp += 1
            
    fn = len(gt_boxes) - len(matched_gt)
    return tp, fp, fn

def load_yolo_ground_truth(label_path, img_width, img_height):
    boxes = []
    labels = []
    if not os.path.exists(label_path):
        return np.zeros((0, 4), dtype=np.float32), np.zeros(0, dtype=np.int64)
    with open(label_path, "r") as f:
        for line in f:
            parts = line.strip().split()
            if len(parts) < 5:
                continue
            cls_id = int(parts[0])
            x_c, y_c, w, h = map(float, parts[1:5])
            
            xmin = (x_c - w / 2) * img_width
            ymin = (y_c - h / 2) * img_height
            xmax = (x_c + w / 2) * img_width
            ymax = (y_c + h / 2) * img_height
            
            boxes.append([xmin, ymin, xmax, ymax])
            labels.append(cls_id)
            
    if not boxes:
        return np.zeros((0, 4), dtype=np.float32), np.zeros(0, dtype=np.int64)
    return np.array(boxes, dtype=np.float32), np.array(labels, dtype=np.int64)

def save_annotated_image(image_path, gt_boxes, yolo_boxes, yolo_scores, kept_indices, captions, output_path):
    # Load original image using PIL
    image_left = Image.open(image_path).convert("RGB")
    image_right = Image.open(image_path).convert("RGB")
    width, height = image_left.size
    
    draw_left = ImageDraw.Draw(image_left)
    draw_right = ImageDraw.Draw(image_right)
    
    # Draw Ground Truth boxes on the left image (Blue)
    for idx, box in enumerate(gt_boxes):
        xmin, ymin, xmax, ymax = box
        # Draw box outline
        for offset in range(3):
            draw_left.rectangle(
                [xmin - offset, ymin - offset, xmax + offset, ymax + offset],
                outline=(0, 0, 255)
            )
        # Draw text label
        draw_left.text((xmin + 2, ymin + 2), "GT Weapon", fill=(0, 0, 255))
        
    # Draw YOLO boxes on the right image
    for idx, (box, score) in enumerate(zip(yolo_boxes, yolo_scores)):
        is_kept = idx in kept_indices
        color = (0, 255, 0) if is_kept else (255, 0, 0) # Green for kept, Red for discarded
        xmin, ymin, xmax, ymax = box
        
        # Draw box outline
        for offset in range(3):
            draw_right.rectangle(
                [xmin - offset, ymin - offset, xmax + offset, ymax + offset],
                outline=color
            )
            
        # Draw simple text label
        label = f"BBox {idx}: Conf={score:.2f} ({'Kept' if is_kept else 'Discarded'})"
        draw_right.text((xmin + 2, ymin + 2), label, fill=color)
        
    # Expand canvas downwards for captions
    lines = []
    lines.append("=== QWEN-VL VALIDATOR DECISIONS ===")
    if not yolo_boxes:
        lines.append("No objects detected by YOLO.")
    else:
        for idx, (box, score) in enumerate(zip(yolo_boxes, yolo_scores)):
            is_kept = idx in kept_indices
            status = "KEPT" if is_kept else "DISCARDED"
            caption_clean = captions.get(idx, "N/A").replace('\n', ' ').strip()
            
            # Simple text wrapping to fit image width (approx 160-180 chars for side-by-side)
            words = caption_clean.split()
            current_line = f"BBox {idx} [{status}]:"
            for word in words:
                if len(current_line) + len(word) > 160:
                    lines.append(current_line)
                    current_line = "    " + word
                else:
                    current_line += " " + word
            lines.append(current_line)
            
    line_height = 20
    top_padding = 30
    extra_height = len(lines) * line_height + 30
    
    combined_width = width * 2
    combined_height = top_padding + height + extra_height
    
    new_image = Image.new("RGB", (combined_width, combined_height), (255, 255, 255))
    
    # Draw headers
    draw_header = ImageDraw.Draw(new_image)
    draw_header.text((15, 8), "GROUND TRUTH (Blue Bboxes)", fill=(0, 0, 255))
    draw_header.text((width + 15, 8), "YOLO + VLM PREDICTIONS (Green=Kept, Red=Discarded)", fill=(0, 128, 0))
    
    # Paste images
    new_image.paste(image_left, (0, top_padding))
    new_image.paste(image_right, (width, top_padding))
    
    # Draw captions
    draw_caption = ImageDraw.Draw(new_image)
    y_offset = top_padding + height + 15
    for line in lines:
        draw_caption.text((15, y_offset), line, fill=(0, 0, 0))
        y_offset += line_height
        
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    new_image.save(output_path)

def main():
    args = parse_args()
    
    device = "cuda" if torch.cuda.is_available() and args.device == "cuda" else "cpu"
    print(f"Using device: {device}")
    
    # Resolve YOLO weights paths
    if args.yolo_models:
        yolo_paths = [p.strip() for p in args.yolo_models.split(",") if p.strip()]
    else:
        default_variants = ["yolo26n", "yolo26s", "yolo26m", "yolo26l", "yolo26x"]
        yolo_paths = []
        for var in default_variants:
            p = f"runs/detect/{var}/weights/best.pt"
            if os.path.exists(p):
                yolo_paths.append(p)
            else:
                print(f"[WARNING] YOLO weights not found for {var} at: {p}")
        if not yolo_paths:
            print("[ERROR] No YOLO weights found under runs/detect/. Please specify --yolo-models manually.")
            sys.exit(1)
            
    print(f"YOLO models to evaluate: {yolo_paths}")
    
    # 2. Load Qwen-VL model + adapter ONCE
    print(f"Loading Qwen-VL adapter from: {args.qwen_model}")
    base_model_id = "Qwen/Qwen3-VL-8B-Instruct"
    
    bnb_config = BitsAndBytesConfig(
        load_in_4bit=True,
        bnb_4bit_compute_dtype=torch.float16,
        bnb_4bit_use_double_quant=True
    )
    
    print("Loading base Qwen3-VL-8B-Instruct model in 4-bit...")
    base_model = Qwen3VLForConditionalGeneration.from_pretrained(
        base_model_id,
        quantization_config=bnb_config,
        device_map={"": 0},
        low_cpu_mem_usage=True,
        torch_dtype=torch.float16
    )
    print("Applying fine-tuned LoRA adapters...")
    qwen_model = PeftModel.from_pretrained(base_model, args.qwen_model)
    qwen_model.eval()
    
    processor = AutoProcessor.from_pretrained(
        args.qwen_model,
        min_pixels=256 * 256,
        max_pixels=args.max_pixels
    )
    
    # 3. Locate dataset test split
    test_images_dir = os.path.join(args.dataset_dir, "test", "images")
    test_labels_dir = os.path.join(args.dataset_dir, "test", "labels")
    
    if not os.path.exists(test_images_dir):
        print(f"[ERROR] Test images directory not found at: {test_images_dir}")
        sys.exit(1)
        
    image_files = glob.glob(os.path.join(test_images_dir, "*.jpg")) + glob.glob(os.path.join(test_images_dir, "*.png"))
    image_files = sorted(image_files)
    if args.max_images is not None:
        image_files = image_files[:args.max_images]
        print(f"Evaluating a subset of {len(image_files)} images...")
    else:
        print(f"Evaluating entire test split ({len(image_files)} images)...")
        
    # Initialize report file
    if args.txt_output:
        with open(args.txt_output, "w", encoding="utf-8") as f:
            f.write("============================================================\n")
            f.write(" JOINT YOLO + VLM EVALUATION COMPARISON REPORT\n")
            f.write("============================================================\n\n")
            
    # 4. Loop over YOLO models
    for yolo_path in yolo_paths:
        model_name = os.path.splitext(os.path.basename(yolo_path))[0]
        # Use parent folder name to distinguish variants (e.g. yolo12n vs yolo12s)
        variant_name = os.path.basename(os.path.dirname(os.path.dirname(yolo_path)))
        unique_model_id = f"{variant_name}_{model_name}"
        
        print("\n" + "="*80)
        print(f"Evaluating YOLO Model: {yolo_path} ({unique_model_id})")
        print("="*80 + "\n")
        
        # Load YOLO model
        yolo_model = YOLO(yolo_path)
        
        preds_without_vlm = []
        preds_with_vlm = []
        targets_list = []
        
        total_tp_no, total_fp_no, total_fn_no = 0, 0, 0
        total_tp_w, total_fp_w, total_fn_w = 0, 0, 0
        
        # Loop through images
        for img_path in tqdm(image_files, desc=f"Inference Progress ({unique_model_id})"):
            filename = os.path.basename(img_path)
            
            # Load PIL image for Qwen
            image_pil = Image.open(img_path).convert("RGB")
            width, height = image_pil.size
            
            # Load ground truths
            label_filename = os.path.splitext(filename)[0] + ".txt"
            label_path = os.path.join(test_labels_dir, label_filename)
            gt_boxes, gt_labels = load_yolo_ground_truth(label_path, width, height)
            
            # Run YOLO inference
            results = yolo_model.predict(img_path, conf=args.conf_thres, iou=args.iou_thres, verbose=False)[0]
            
            yolo_boxes = []
            yolo_scores = []
            
            if results.boxes is not None:
                for box_obj in results.boxes:
                    cls_id = int(box_obj.cls[0].item())
                    if cls_id == 0:
                        conf = float(box_obj.conf[0].item())
                        xyxy = box_obj.xyxy[0].tolist()
                        yolo_boxes.append(xyxy)
                        yolo_scores.append(conf)
                        
            # VLM verification
            vlm_boxes = []
            vlm_scores = []
            kept_indices = []
            captions = {}
            
            if yolo_boxes and device == "cuda":
                prompts = []
                img_list = []
                vlm_check_indices = []
                
                for idx, (box, conf) in enumerate(zip(yolo_boxes, yolo_scores)):
                    if conf >= args.vlm_bypass_thres:
                        # Bypass VLM check for highly confident YOLO detections
                        vlm_boxes.append(box)
                        vlm_scores.append(conf)
                        kept_indices.append(idx)
                        captions[idx] = f"VLM verification bypassed (YOLO confidence {conf:.2f} >= {args.vlm_bypass_thres:.2f})"
                    else:
                        vlm_check_indices.append(idx)
                        xmin, ymin, xmax, ymax = box
                        box_str = format_qwen_bbox(xmin, ymin, xmax, ymax, width, height)
                        user_text = f"Analyze the object located inside the grounding bounding box {box_str} and determine whether the object is a real firearm or a visually similar non-weapon object."
                        prompt = SYSTEM_PROMPT + f"<|im_start|>user\n<|vision_start|><|image_pad|><|vision_end|>{user_text}<|im_end|>\n" + ASSISTANT_PREFIX
                        prompts.append(prompt)
                        img_list.append(image_pil)
                        
                if prompts:
                    # Chunk generation to prevent OOM
                    chunk_size = 4
                    output_texts = []
                    for i in range(0, len(prompts), chunk_size):
                        chunk_prompts = prompts[i:i+chunk_size]
                        chunk_images = img_list[i:i+chunk_size]
                        
                        inputs = processor(
                            text=chunk_prompts,
                            images=chunk_images,
                            padding=True,
                            return_tensors="pt"
                        )
                        inputs = {k: v.to(device) for k, v in inputs.items()}
                        
                        with torch.no_grad():
                            generated_ids = qwen_model.generate(**inputs, max_new_tokens=args.max_new_tokens)
                            
                        generated_ids_trimmed = [
                            out_ids[len(in_ids) :] for in_ids, out_ids in zip(inputs["input_ids"], generated_ids)
                        ]
                        chunk_outputs = processor.batch_decode(
                            generated_ids_trimmed, skip_special_tokens=True, clean_up_tokenization_spaces=False
                        )
                        output_texts.extend(chunk_outputs)
                        
                    # Verify and filter
                    for idx, output_text in zip(vlm_check_indices, output_texts):
                        output_clean = output_text.strip()
                        captions[idx] = output_clean
                        
                        is_weapon = False
                        if "Final Decision: Weapon" in output_clean:
                            is_weapon = True
                        elif "Final Decision: Non-Weapon" in output_clean:
                            is_weapon = False
                        else:
                            is_weapon = "non-weapon" not in output_clean.lower() and "weapon" in output_clean.lower()
                            
                        if is_weapon:
                            vlm_boxes.append(yolo_boxes[idx])
                            vlm_scores.append(yolo_scores[idx])
                            kept_indices.append(idx)
            else:
                # If running on CPU or no detections, skip VLM and just copy boxes
                vlm_boxes = list(yolo_boxes)
                vlm_scores = list(yolo_scores)
                kept_indices = list(range(len(yolo_boxes)))
                captions = {idx: "VLM verification skipped (running on CPU/no detections)" for idx in range(len(yolo_boxes))}
                
            # Store for mAP calculation
            target_boxes_t = torch.tensor(gt_boxes, dtype=torch.float32)
            target_labels_t = torch.tensor(gt_labels, dtype=torch.int64)
            targets_list.append({"boxes": target_boxes_t, "labels": target_labels_t})
            
            yolo_boxes_t = torch.tensor(yolo_boxes, dtype=torch.float32).reshape(-1, 4)
            yolo_scores_t = torch.tensor(yolo_scores, dtype=torch.float32).reshape(-1)
            yolo_labels_t = torch.zeros(len(yolo_boxes), dtype=torch.int64)
            preds_without_vlm.append({"boxes": yolo_boxes_t, "scores": yolo_scores_t, "labels": yolo_labels_t})
            
            vlm_boxes_t = torch.tensor(vlm_boxes, dtype=torch.float32).reshape(-1, 4)
            vlm_scores_t = torch.tensor(vlm_scores, dtype=torch.float32).reshape(-1)
            vlm_labels_t = torch.zeros(len(vlm_boxes), dtype=torch.int64)
            preds_with_vlm.append({"boxes": vlm_boxes_t, "scores": vlm_scores_t, "labels": vlm_labels_t})
            
            # Calculate TP, FP, FN at IoU 0.5
            tp_no, fp_no, fn_no = compute_image_tp_fp_fn(np.array(yolo_boxes), np.array(yolo_scores), gt_boxes)
            tp_w, fp_w, fn_w = compute_image_tp_fp_fn(np.array(vlm_boxes), np.array(vlm_scores), gt_boxes)
            
            total_tp_no += tp_no
            total_fp_no += fp_no
            total_fn_no += fn_no
            
            total_tp_w += tp_w
            total_fp_w += fp_w
            total_fn_w += fn_w
            
            # Save annotated image output if requested
            if args.output_dir:
                img_out_path = os.path.join(args.output_dir, unique_model_id, filename)
                save_annotated_image(img_path, gt_boxes, yolo_boxes, yolo_scores, kept_indices, captions, img_out_path)
                
        # Compute Metrics
        print("\nComputing average precision (mAP) metrics...")
        metric_no_vlm = MeanAveragePrecision(box_format="xyxy", iou_type="bbox")
        metric_no_vlm.update(preds_without_vlm, targets_list)
        results_no_vlm = metric_no_vlm.compute()
        
        metric_with_vlm = MeanAveragePrecision(box_format="xyxy", iou_type="bbox")
        metric_with_vlm.update(preds_with_vlm, targets_list)
        results_with_vlm = metric_with_vlm.compute()
        
        # Calculate dataset-wide Precision & Recall
        prec_no = total_tp_no / (total_tp_no + total_fp_no) if (total_tp_no + total_fp_no) > 0 else 0.0
        rec_no = total_tp_no / (total_tp_no + total_fn_no) if (total_tp_no + total_fn_no) > 0 else 0.0
        
        prec_w = total_tp_w / (total_tp_w + total_fp_w) if (total_tp_w + total_fp_w) > 0 else 0.0
        rec_w = total_tp_w / (total_tp_w + total_fn_w) if (total_tp_w + total_fn_w) > 0 else 0.0
        
        # Calculate FPPI (False Positives Per Image)
        fppi_no = total_fp_no / len(image_files)
        fppi_w = total_fp_w / len(image_files)
        
        # Calculate reduction in FPs
        fp_reduction = ((total_fp_no - total_fp_w) / total_fp_no * 100) if total_fp_no > 0 else 0.0
        
        # Format Report
        diff_map50 = results_with_vlm["map_50"].item() - results_no_vlm["map_50"].item()
        diff_map75 = results_with_vlm["map_75"].item() - results_no_vlm["map_75"].item()
        diff_map = results_with_vlm["map"].item() - results_no_vlm["map"].item()
        diff_prec = prec_w - prec_no
        diff_rec = rec_w - rec_no
        
        report = []
        report.append("="*60)
        report.append(f" MODEL REPORT: {unique_model_id}")
        report.append("="*60)
        report.append(f"YOLO Model Weights : {yolo_path}")
        report.append(f"Qwen-VL Adapter    : {args.qwen_model}")
        report.append(f"Total Test Images  : {len(image_files)}")
        if args.output_dir:
            report.append(f"Annotated Images   : {os.path.join(args.output_dir, unique_model_id)}")
        report.append("-"*60)
        report.append(f"{'Metric':<25} | {'YOLO Only':<12} | {'YOLO + VLM':<12} | {'Difference':<10}")
        report.append("-"*60)
        report.append(f"{'mAP50 (IoU=0.50)':<25} | {results_no_vlm['map_50'].item():<12.4f} | {results_with_vlm['map_50'].item():<12.4f} | {diff_map50:+.4f}")
        report.append(f"{'mAP75 (IoU=0.75)':<25} | {results_no_vlm['map_75'].item():<12.4f} | {results_with_vlm['map_75'].item():<12.4f} | {diff_map75:+.4f}")
        report.append(f"{'mAP50-95 (COCO)':<25} | {results_no_vlm['map'].item():<12.4f} | {results_with_vlm['map'].item():<12.4f} | {diff_map:+.4f}")
        report.append(f"{'Precision':<25} | {prec_no:<12.4f} | {prec_w:<12.4f} | {diff_prec:+.4f}")
        report.append(f"{'Recall':<25} | {rec_no:<12.4f} | {rec_w:<12.4f} | {diff_rec:+.4f}")
        report.append("-"*60)
        report.append(f"Total True Positives (TP) : {total_tp_no:<12} | {total_tp_w:<12} | Difference: {total_tp_w - total_tp_no}")
        report.append(f"Total False Positives (FP): {total_fp_no:<12} | {total_fp_w:<12} | Difference: {total_fp_w - total_fp_no}")
        report.append(f"False Positives / Image   : {fppi_no:<12.4f} | {fppi_w:<12.4f} | Difference: {fppi_w - fppi_no:+.4f}")
        report.append(f"Total False Negatives (FN): {total_fn_no:<12} | {total_fn_w:<12} | Difference: {total_fn_w - total_fn_no}")
        report.append("-"*60)
        report.append(f"==> False Positive Reduction Rate: {fp_reduction:.2f}%")
        report.append("="*60 + "\n\n")
        
        report_str = "\n".join(report)
        print(report_str)
        
        # Save output to text file
        if args.txt_output:
            with open(args.txt_output, "a", encoding="utf-8") as f:
                f.write(report_str)
                
        # Clean up YOLO model to release memory before next load
        del yolo_model
        gc.collect()
        if torch.cuda.is_available():
            torch.cuda.empty_cache()
            
    print(f"All model evaluations completed. Results saved to {args.txt_output}")

if __name__ == "__main__":
    main()
